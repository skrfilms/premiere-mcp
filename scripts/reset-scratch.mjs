// Shared ExtendScript helpers. ES3 — no let/const/arrow/Set/Map/forEach/indexOf-on-arrays.
// ---------------------------------------------------------------------------------------------
const HELPERS = `
  function findRootItemByName(nm) {
    var root = app.project.rootItem;
    for (var i = 0; i < root.children.numItems; i++) {
      if (String(root.children[i].name) === nm) return root.children[i];
    }
    return null;
  }
  function findRootItemContaining(frag) {
    var root = app.project.rootItem;
    for (var i = 0; i < root.children.numItems; i++) {
      if (String(root.children[i].name).indexOf(frag) !== -1) return root.children[i];
    }
    return null;
  }
  // deleteBin() only removes bins; on a footage clip it silently no-ops. Route clips through a
  // throwaway bin and delete that wholesale — the same technique expanded.ts already relies on.
  function deleteAnyItem(item) {
    try {
      if (item.type === 2) { item.deleteBin(); return true; }
      var tmp = app.project.rootItem.createBin('__reset_tmp__');
      if (!tmp) return false;
      item.moveBin(tmp);
      tmp.deleteBin();
      return true;
    } catch (e) { return false; }
  }
`;

const steps = [];
const record = (label, detail) => { steps.push({ label, detail }); console.log(`- ${label}: ${detail}`); };

// 1. Strip the project bare. Offline items are the specific danger: they are what makes
//    Premiere raise Link Media on the next open, which would break auto-recovery.
{
  const r = await host('wipe', `(function(){
    ${HELPERS}
    var removedSeqs = 0, removedItems = 0, failures = [];
    // Sequences first: deleting a sequence's ProjectItem out from under it is unreliable.
    var guard = 0;
    while (app.project.sequences.numSequences > 0 && guard++ < 50) {
      var before = app.project.sequences.numSequences;
      try { app.project.deleteSequence(app.project.sequences[0]); } catch (e) { failures.push('seq: ' + e.toString()); break; }
      if (app.project.sequences.numSequences >= before) { failures.push('sequence count did not drop'); break; }
      removedSeqs++;
    }
    // Skip past an item that will not go rather than stopping at it: stopping left everything
    // behind it in place too, and those leftovers sorted ahead of the fresh fixture.
    var guard2 = 0, at = 0;
    while (at < app.project.rootItem.children.numItems && guard2++ < 400) {
      var item = app.project.rootItem.children[at];
      var nm = String(item.name), id = String(item.nodeId);
      var before2 = app.project.rootItem.children.numItems;
      deleteAnyItem(item);
      var still = at < app.project.rootItem.children.numItems && String(app.project.rootItem.children[at].nodeId) === id;
      if (still || app.project.rootItem.children.numItems >= before2) { failures.push('item ' + nm + ' survived deletion'); at++; continue; }
      removedItems++;
    }
    return JSON.stringify({
      removedSeqs: removedSeqs, removedItems: removedItems,
      remainingItems: app.project.rootItem.children.numItems,
      remainingSeqs: app.project.sequences.numSequences,
      failures: failures
    });
  })();`);
  record('wipe', `${r.removedSeqs} sequences, ${r.removedItems} items removed; ${r.remainingItems} items / ${r.remainingSeqs} sequences remain${r.failures.length ? '; FAILURES: ' + r.failures.join(' | ') : ''}`);
}

// 1b. Ingest off. With Project Settings > Ingest set to "copy", every importFiles() writes a fresh
//     numbered copy of the media (fixture_a_151.mp4 ...), and the fixture then points at the copy.
//     A sweep run of set_transcode_on_ingest switched it on once and ~600 copies piled up in
//     .scratch/media before anyone noticed. The setting lives in the .prproj, so the wipe above does
//     not clear it.
{
  const r = await host('ingest', `(function(){
    var r = null;
    try { r = app.project.setEnableTranscodeOnIngest(false); } catch (e) { return JSON.stringify({ ok: false, error: e.toString() }); }
    return JSON.stringify({ ok: true, result: String(r) });
  })();`);
  record('ingest', r.ok ? 'copy/transcode on import disabled' : `could not disable: ${r.error}`);
}

// 2. Import the synthetic media. importFiles(paths, suppressUI, targetBin, numberedStills).
{
  const paths = JSON.stringify([...CLIPS, STILL]);
  const r = await host('import', `(function(){
    ${HELPERS}
    var paths = ${paths};
    var ok = false;
    try { ok = app.project.importFiles(paths, true, app.project.rootItem, false); } catch (e) {
      return JSON.stringify({ ok: false, error: e.toString() });
    }
    var names = [];
    for (var i = 0; i < app.project.rootItem.children.numItems; i++) names.push(String(app.project.rootItem.children[i].name));
    return JSON.stringify({ ok: ok, count: app.project.rootItem.children.numItems, names: names });
  })();`);
  if (!r.count) throw new Error(`import produced no project items: ${JSON.stringify(r)}`);
  record('import', `${r.count} items: ${r.names.join(', ')}`);
}

// 3. Build the sequence from fixture_a so sequence settings match the media exactly. A matching
//    sequence is what keeps overwriteClip from raising the Clip Mismatch Warning later.
{
  const r = await host('sequence', `(function(){
    ${HELPERS}
    var a = findRootItemContaining('fixture_a');
    if (!a) return JSON.stringify({ ok: false, error: 'fixture_a not found after import' });
    var seq = null;
    try { seq = app.project.createNewSequenceFromClips('fixture_seq_a', [a], app.project.rootItem); } catch (e) {
      return JSON.stringify({ ok: false, error: 'createNewSequenceFromClips: ' + e.toString() });
    }
    if (!seq) return JSON.stringify({ ok: false, error: 'createNewSequenceFromClips returned null' });
    app.project.openSequence(seq.sequenceID);
    return JSON.stringify({
      ok: true, name: String(seq.name),
      vTracks: seq.videoTracks.numTracks, aTracks: seq.audioTracks.numTracks,
      w: seq.frameSizeHorizontal, h: seq.frameSizeVertical
    });
  })();`);
  if (!r.ok) throw new Error(`sequence build failed: ${r.error}`);
  record('sequence', `"${r.name}" ${r.w}x${r.h}, ${r.vTracks}V/${r.aTracks}A`);
}

// 4. Guarantee at least 3 video / 2 audio tracks — several tools address V2/V3 or A2 directly.
{
  const r = await host('tracks', `(function(){
    var seq = app.project.activeSequence;
    app.enableQE();
    var q = qe.project.getActiveSequence();
    var guard = 0;
    while (seq.videoTracks.numTracks < 3 && guard++ < 6) q.addTracks(1, seq.videoTracks.numTracks, 0, 0, 0, 0, 0, 0);
    guard = 0;
    while (seq.audioTracks.numTracks < 2 && guard++ < 6) q.addTracks(0, 0, 0, 1, seq.audioTracks.numTracks, 0, 0, 0);
    return JSON.stringify({ vTracks: seq.videoTracks.numTracks, aTracks: seq.audioTracks.numTracks });
  })();`);
  record('tracks', `${r.vTracks}V / ${r.aTracks}A`);
}

// 5. Populate the timeline: b appended after a on V1, c stacked on V2. Two clips on one track is
//    what makes edit-point, ripple, roll, and gap tools meaningful.
{
  const r = await host('populate', `(function(){
    ${HELPERS}
    var seq = app.project.activeSequence;
    var b = findRootItemContaining('fixture_b');
    var c = findRootItemContaining('fixture_c');
    var v1 = seq.videoTracks[0], v2 = seq.videoTracks[1];
    var errs = [];
    if (b && v1.clips.numItems < 2) {
      var t = new Time();
      t.ticks = String(v1.clips[v1.clips.numItems - 1].end.ticks);
      try { v1.overwriteClip(b, t); } catch (e) { errs.push('v1 overwrite: ' + e.toString()); }
    }
    if (c && v2 && v2.clips.numItems < 1) {
      var t2 = new Time(); t2.ticks = '0';
      try { v2.overwriteClip(c, t2); } catch (e) { errs.push('v2 overwrite: ' + e.toString()); }
    }
    return JSON.stringify({
      v1: v1.clips.numItems, v2: v2 ? v2.clips.numItems : 0,
      a1: seq.audioTracks.numTracks > 0 ? seq.audioTracks[0].clips.numItems : 0,
      errors: errs
    });
  })();`);
  record('populate', `V1=${r.v1} clips, V2=${r.v2}, A1=${r.a1}${r.errors.length ? '; errors: ' + r.errors.join(' | ') : ''}`);
}

// 6. Lumetri on the first clip. applyLumetriPreset is the reliable path (fingerprint-verified
//    previously); the QE add is the fallback. Eight Lumetri tools are untestable without this.
{
  const r = await host('lumetri', `(function(){
    var seq = app.project.activeSequence;
    var clip = seq.videoTracks[0].clips[0];
    if (!clip) return JSON.stringify({ ok: false, error: 'no clip on V1' });
    function hasLumetri() {
      for (var i = 0; i < clip.components.numItems; i++) {
        if (String(clip.components[i].displayName).indexOf('Lumetri') !== -1) return true;
      }
      return false;
    }
    var before = hasLumetri();
    if (!before) {
      app.enableQE();
      try {
        var qclip = qe.project.getActiveSequence().getVideoTrackAt(0).getItemAt(0);
        var eff = qe.project.getVideoEffectByName('Lumetri Color');
        if (eff) qclip.addVideoEffect(eff);
      } catch (e) {}
    }
    var names = [];
    for (var j = 0; j < clip.components.numItems; j++) names.push(String(clip.components[j].displayName));
    return JSON.stringify({ ok: hasLumetri(), wasAlreadyThere: before, components: names });
  })();`);
  record('lumetri', r.ok ? `present; stack = ${r.components.join(' > ')}` : `NOT APPLIED — stack = ${r.components.join(' > ')}`);
}

// 7. Markers: a Comment with text plus two Chapters, for the marker/chapter/segment families.
{
  const r = await host('markers', `(function(){
    var m = app.project.activeSequence.markers;
    if (m.numMarkers < 3) {
      var a = m.createMarker(0.5); a.name = 'fixture_comment'; a.comments = 'TODO check this beat'; a.type = 'Comment';
      var b = m.createMarker(1.5); b.name = 'Chapter One'; b.type = 'Chapter';
      var c = m.createMarker(3.0); c.name = 'Chapter Two'; c.type = 'Chapter';
    }
    return JSON.stringify({ count: m.numMarkers });
  })();`);
  record('markers', `${r.count} markers`);
}

// 8. Sequence in/out points — the export-range family reads these.
{
  const r = await host('inout', `(function(){
    var seq = app.project.activeSequence;
    seq.setInPoint(0); seq.setOutPoint(2);
    return JSON.stringify({ inSecs: seq.getInPoint().seconds, outSecs: seq.getOutPoint().seconds });
  })();`);
  record('in/out', `${r.inSecs}s -> ${r.outSecs}s`);
}

// 9. A bin, and a second sequence for the cross-sequence tools (copy markers, conform, diff).
{
  const r = await host('bin+seq2', `(function(){
    ${HELPERS}
    var bin = findRootItemByName('fixture_bin');
    if (!bin) bin = app.project.rootItem.createBin('fixture_bin');
    var second = null;
    for (var i = 0; i < app.project.sequences.numSequences; i++) {
      if (String(app.project.sequences[i].name).indexOf('fixture_seq_b') !== -1) { second = app.project.sequences[i]; break; }
    }
    if (!second) {
      var src = app.project.activeSequence;
      try {
        var dup = src.clone();
        for (var j = 0; j < app.project.sequences.numSequences; j++) {
          var nm = String(app.project.sequences[j].name);
          if (nm.indexOf('Copy') !== -1) { app.project.sequences[j].projectItem.name = 'fixture_seq_b'; second = app.project.sequences[j]; break; }
        }
      } catch (e) { return JSON.stringify({ bin: !!bin, second: null, error: e.toString() }); }
    }
    // clone() makes the copy current; restore fixture_seq_a as the active sequence so every
    // later step and every sweep starts from a known sequence.
    for (var k = 0; k < app.project.sequences.numSequences; k++) {
      if (String(app.project.sequences[k].name) === 'fixture_seq_a') { app.project.openSequence(app.project.sequences[k].sequenceID); break; }
    }
    return JSON.stringify({
      bin: bin ? String(bin.name) : null,
      second: second ? String(second.name) : null,
      sequences: app.project.sequences.numSequences,
      active: String(app.project.activeSequence.name)
    });
  })();`);
  record('bin+seq2', `bin=${r.bin}, second=${r.second}, sequences=${r.sequences}, active=${r.active}`);
}

// 10. An SRT on disk. The caption-file family reads the filesystem and never touches the host.
writeFileSync(SRT_PATH, [
  '1', '00:00:00,000 --> 00:00:01,500', 'First fixture caption line.', '',
  '2', '00:00:01,600 --> 00:00:03,000', 'Second fixture caption line.', '',
  '3', '00:00:03,100 --> 00:00:04,000', 'Third fixture caption line.', '',
].join('\n'));
record('srt', SRT_PATH);

// 10b. Camera angles into fixture_bin, so the bin-driven tools (create_sequence_from_bin,
//      storyboard_bin_to_sequence, create_multicam_source_sequence) have clips to build from.
//      An empty bin made every one of them refuse — correctly, and on every sweep.
{
  const r = await host('cams', `(function(){
    ${HELPERS}
    var bin = findRootItemByName('fixture_bin');
    if (!bin) return JSON.stringify({ ok: false, error: 'fixture_bin missing' });
    if (bin.children.numItems === 0) app.project.importFiles(${JSON.stringify(CAMS)}, true, bin, false);
    return JSON.stringify({ ok: true, count: bin.children.numItems });
  })();`);
  record('cams', `${r.count} angle clips in fixture_bin`);
}

// 10c. A real multicam: import the multiclip XML into its own bin. This also creates
//      fixture_mc_edit, a sequence whose V1 clip is the multicam, for the clip-level multicam tools.
{
  // The XML import raises a Translation Report just after it returns; the guard lingers for it.
  const { withReportDialogGuard } = await import('../dist/bridge/report-dialog-guard.js');
  const { result: r } = await withReportDialogGuard(() => host('multicam', `(function(){
    ${HELPERS}
    var bin = findRootItemByName('fixture_multicam_bin');
    if (!bin) {
      bin = app.project.rootItem.createBin('fixture_multicam_bin');
      app.project.importFiles([${JSON.stringify(MULTICAM_XML)}], true, bin, false);
    }
    var mc = null;
    for (var i = 0; i < bin.children.numItems; i++) {
      try { if (bin.children[i].isMulticamClip()) { mc = bin.children[i]; break; } } catch (e) {}
    }
    var edit = null;
    for (var s = 0; s < app.project.sequences.numSequences; s++) {
      if (String(app.project.sequences[s].name) === 'fixture_mc_edit') edit = app.project.sequences[s];
    }
    return JSON.stringify({ multicam: mc ? String(mc.name) : null, edit: edit ? String(edit.name) : null });
  })();`), { lingerMs: 8000 });
  record('multicam', r.multicam ? `multicam item "${r.multicam}", edit sequence ${r.edit}` : 'NOT CREATED — the XML import yielded no multicam item');
}

// 10d. The SRT as a project item plus a caption track built from it. create_caption_track needs a
//      caption project item to point at; with none in the project it could only report "not found".
{
  const r = await host('captions', `(function(){
    ${HELPERS}
    var item = findRootItemByName('fixture-captions.srt');
    if (!item) {
      app.project.importFiles([${JSON.stringify(SRT_PATH)}], true, app.project.rootItem, false);
      item = findRootItemByName('fixture-captions.srt');
    }
    if (!item) return JSON.stringify({ ok: false, error: 'SRT import produced no project item' });
    var made = false;
    try { made = app.project.activeSequence.createCaptionTrack(item, 0, Sequence.CAPTION_FORMAT_SUBTITLE); } catch (e) {
      return JSON.stringify({ ok: false, error: 'createCaptionTrack: ' + e.toString() });
    }
    return JSON.stringify({ ok: true, made: String(made) });
  })();`);
  // There is no caption read API, so "made" is Premiere's own return value, not a readback.
  record('captions', r.ok ? `SRT imported; createCaptionTrack returned ${r.made}` : `FAILED: ${r.error}`);
}

// 10e. A MOGRT on V3 so the MOGRT family (set_mogrt_text/param/color, mogrt_params_report) has an
//      isMGT() clip to address. At 20s, past the V1/V2 content: placed at 0 it spanned the V1 edit
//      points, and the ripple tools (correctly) refused to ripple V1 under it.
if (existsSync(MOGRT)) {
  const r = await host('mogrt', `(function(){
    var seq = app.project.activeSequence;
    var v3 = seq.videoTracks[2];
    for (var i = 0; i < v3.clips.numItems; i++) {
      if (v3.clips[i].isMGT() && v3.clips[i].getMGTComponent()) return JSON.stringify({ ok: true, already: true, name: String(v3.clips[i].name) });
    }
    var t = new Time(); t.seconds = 20;
    var clip = seq.importMGT(${JSON.stringify(MOGRT)}, t.ticks, 2, 2);
    return JSON.stringify({ ok: !!(clip && clip.getMGTComponent()), name: clip ? String(clip.name) : null });
  })();`);
  record('mogrt', r.ok ? `"${r.name}" on V3${r.already ? ' (already there)' : ''}` : 'NOT USABLE — importMGT returned no clip with an MGT component');
} else {
  record('mogrt', `SKIPPED — no template at ${MOGRT} (set PREMIERE_MCP_FIXTURE_MOGRT)`);
}

